    fun isKnown(name: String) = name in allowed

    fun isAllowed(name: String, tag: String, value: String?): Boolean {
        if (allowed[name] != tag || !BackupSecurity.exportablePreference(name)) return false
        return when (tag) {
            "boolean" -> value == "true" || value == "false"
            "int" -> value?.toIntOrNull() != null
            "long" -> value?.toLongOrNull() != null
            "float" -> value?.toFloatOrNull()?.isFinite() == true
            "string" -> value != null && value.length <= 32_768
            "string-set" -> value == null
            else -> false
        }
    }
